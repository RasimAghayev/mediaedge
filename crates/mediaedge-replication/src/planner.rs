//! Replication Planner - Intelligent replica placement
//!
//! Features:
//! - Continent/region staging
//! - Demand-triggered local replicas
//! - Storage capacity awareness
//! - Anti-affinity (nearby nodes not redundant mirrors)
//! - Cost optimization

use std::collections::{HashMap, HashSet};
use std::sync::Arc;

use dashmap::DashMap;
use serde::{Deserialize, Serialize};
use tracing::{debug, info, warn};

use crate::erasure::ErasureConfig;
use mediaedge_config::types::{ReplicationCoordinatorConfig, StorageNodeConfig};
use mediaedge_observability::MetricsRegistry;

/// Replication planner configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlannerConfig {
    /// Enable continent-level staging.
    #[serde(default = "default_true")]
    pub continent_staging: bool,

    /// Enable region-level staging.
    #[serde(default = "default_true")]
    pub region_staging: bool,

    /// Anti-affinity: minimum distance between replicas.
    #[serde(default = "default_anti_affinity")]
    pub min_anti_affinity_distance: AntiAffinityDistance,

    /// Storage capacity headroom (fraction to keep free).
    #[serde(default = "default_headroom")]
    pub capacity_headroom: f32,

    /// Cost optimization weight (0.0 = performance only, 1.0 = cost only).
    #[serde(default = "default_cost_weight")]
    pub cost_weight: f32,

    /// Max replicas per stream.
    #[serde(default = "default_max_replicas")]
    pub max_replicas_per_stream: u32,
}

fn default_true() -> bool { true }
fn default_anti_affinity() -> AntiAffinityDistance { AntiAffinityDistance::Datacenter }
fn default_headroom() -> f32 { 0.15 }
fn default_cost_weight() -> f32 { 0.3 }
fn default_max_replicas() -> u32 { 6 }

impl Default for PlannerConfig {
    fn default() -> Self {
        Self {
            continent_staging: true,
            region_staging: true,
            min_anti_affinity_distance: AntiAffinityDistance::Datacenter,
            capacity_headroom: 0.15,
            cost_weight: 0.3,
            max_replicas_per_stream: 6,
        }
    }
}

/// Anti-affinity distance levels.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AntiAffinityDistance {
    None,           // No anti-affinity
    Rack,           // Different racks
    Datacenter,     // Different datacenters (default)
    Region,         // Different regions
    Continent,      // Different continents
}

/// Node topology information.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NodeTopology {
    pub node_id: String,
    pub region: String,
    pub continent: String,
    pub datacenter: String,
    pub rack: Option<String>,
    pub storage_capacity_bytes: u64,
    pub storage_used_bytes: u64,
    pub storage_class: StorageClass,
    pub cost_per_gb_month: f64,
    pub bandwidth_mbps: u32,
    pub latency_to_regions: HashMap<String, u32>, // ms
    pub capabilities: NodeCapabilities,
}

/// Node capabilities.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NodeCapabilities {
    pub erasure_coding: bool,
    pub gpu_transcode: bool,
    pub cold_storage: bool,
    pub max_concurrent_streams: u32,
}

impl Default for NodeCapabilities {
    fn default() -> Self {
        Self {
            erasure_coding: true,
            gpu_transcode: false,
            cold_storage: false,
            max_concurrent_streams: 1000,
        }
    }
}

/// Storage class.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum StorageClass {
    Hot,    // NVMe
    Warm,   // SSD
    Cold,   // HDD/Object
}

/// Replication plan generated by planner.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReplicationPlanOutput {
    pub stream_id: String,
    pub primary: PlannedReplica,
    pub replicas: Vec<PlannedReplica>,
    pub erasure_config: ErasureConfig,
    pub staging_plan: Option<StagingPlan>,
    pub demand_triggers: Vec<DemandTriggerPlan>,
    pub estimated_cost_per_month: f64,
    pub durability_score: f32,
}

/// Planned replica.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlannedReplica {
    pub replica_id: String,
    pub node_id: String,
    pub region: String,
    pub datacenter: String,
    pub storage_class: StorageClass,
    pub role: ReplicaRole,
    pub priority: u32,
    pub estimated_latency_ms: u32,
}

/// Replica role.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ReplicaRole {
    Primary,
    Synchronous,    // Sync replication (RPO=0)
    Asynchronous,   // Async replication (RPO>0)
    Staging,        // Temporary staging
    Demand,         // Demand-triggered
}

/// Staging plan for multi-tier replication.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StagingPlan {
    pub continent_staging: Vec<PlannedReplica>,
    pub region_staging: Vec<PlannedReplica>,
    pub promotion_policy: PromotionPolicy,
}

/// Promotion policy for staging replicas.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PromotionPolicy {
    pub trigger: PromotionTrigger,
    pub target_role: ReplicaRole,
    pub max_promotion_time_secs: u32,
}

/// Promotion trigger.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum PromotionTrigger {
    PrimaryFailure,
    LatencyThreshold { max_ms: u32 },
    DemandSpike { min_viewers: u32 },
    Scheduled { cron: String },
}

/// Demand trigger plan.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DemandTriggerPlan {
    pub region: String,
    pub min_viewers: u32,
    pub trigger_delay_secs: u64,
    pub cooldown_secs: u64,
    pub target_replicas: u32,
    pub storage_class: StorageClass,
}

/// Replication planner.
pub struct ReplicationPlanner {
    config: PlannerConfig,
    node_topology: Arc<DashMap<String, NodeTopology>>,
    active_plans: Arc<DashMap<String, ReplicationPlanOutput>>,
    metrics: Arc<MetricsRegistry>,
}

impl ReplicationPlanner {
    /// Create a new replication planner.
    pub fn new(config: PlannerConfig, metrics: Arc<MetricsRegistry>) -> Self {
        Self {
            config,
            node_topology: Arc::new(DashMap::new()),
            active_plans: Arc::new(DashMap::new()),
            metrics,
        }
    }

    /// Register/update node topology.
    pub fn update_node_topology(&self, topology: NodeTopology) {
        self.node_topology.insert(topology.node_id.clone(), topology);
    }

    /// Remove node topology.
    pub fn remove_node_topology(&self, node_id: &str) {
        self.node_topology.remove(node_id);
    }

    /// Plan replication for a stream.
    pub fn plan_replication(
        &self,
        stream_id: String,
        source_region: String,
        target_regions: Vec<TargetRegionInput>,
        erasure_config: ErasureConfig,
        viewer_distribution: HashMap<String, u32>, // region -> viewer count
    ) -> anyhow::Result<ReplicationPlanOutput> {
        info!("Planning replication for stream: {} from {}", stream_id, source_region);

        // Get available nodes
        let nodes: Vec<NodeTopology> = self.node_topology.iter()
            .map(|n| n.value().clone())
            .collect();

        if nodes.is_empty() {
            return Err(anyhow::anyhow!("No nodes available for replication"));
        }

        // Find primary node in source region
        let primary_node = self.select_primary_node(&nodes, &source_region)?;
        
        // Plan replicas
        let replicas = self.plan_replicas(
            &nodes,
            &primary_node,
            &target_regions,
            &viewer_distribution,
            &erasure_config,
        )?;

        // Plan staging if enabled
        let staging_plan = if self.config.continent_staging || self.config.region_staging {
            Some(self.plan_staging(&nodes, &primary_node, &replicas)?)
        } else {
            None
        };

        // Plan demand triggers
        let demand_triggers = self.plan_demand_triggers(&viewer_distribution)?;

        // Calculate estimated cost
        let estimated_cost = self.estimate_cost(&primary_node, &replicas, &staging_plan);

        // Calculate durability score
        let durability = self.calculate_durability(&primary_node, &replicas, &erasure_config);

        let plan = ReplicationPlanOutput {
            stream_id,
            primary: PlannedReplica {
                replica_id: format!("primary-{}", uuid::Uuid::new_v4()),
                node_id: primary_node.node_id.clone(),
                region: primary_node.region.clone(),
                datacenter: primary_node.datacenter.clone(),
                storage_class: primary_node.storage_class,
                role: ReplicaRole::Primary,
                priority: 0,
                estimated_latency_ms: 0,
            },
            replicas,
            erasure_config,
            staging_plan,
            demand_triggers,
            estimated_cost_per_month: estimated_cost,
            durability_score: durability,
        };

        self.active_plans.insert(plan.stream_id.clone(), plan.clone());
        self.metrics.counter("replication_plans_generated_total", "Plans generated").increment(1);

        Ok(plan)
    }

    /// Select primary node in source region.
    fn select_primary_node(&self, nodes: &[NodeTopology], source_region: &str) -> anyhow::Result<NodeTopology> {
        let candidates: Vec<&NodeTopology> = nodes.iter()
            .filter(|n| n.region == source_region)
            .filter(|n| n.storage_class == StorageClass::Hot)
            .collect();

        if candidates.is_empty() {
            return Err(anyhow::anyhow!("No suitable primary node in region: {}", source_region));
        }

        // Select node with most free capacity and lowest cost
        let mut best = candidates[0];
        let mut best_score = f32::MIN;

        for node in candidates {
            let free_ratio = 1.0 - (node.storage_used_bytes as f32 / node.storage_capacity_bytes.max(1) as f32);
            let cost_score = 1.0 / (1.0 + node.cost_per_gb_month as f32);
            let score = free_ratio * 0.7 + cost_score * 0.3;

            if score > best_score {
                best_score = score;
                best = node;
            }
        }

        Ok(best.clone())
    }

    /// Plan replicas for target regions.
    fn plan_replicas(
        &self,
        nodes: &[NodeTopology],
        primary: &NodeTopology,
        target_regions: &[TargetRegionInput],
        viewer_distribution: &HashMap<String, u32>,
        erasure_config: &ErasureConfig,
    ) -> anyhow::Result<Vec<PlannedReplica>> {
        let mut replicas = Vec::new();
        let mut used_nodes = HashSet::new();
        used_nodes.insert(primary.node_id.clone());

        let total_shards = erasure_config.k + erasure_config.m;
        let target_replicas = std::cmp::min(total_shards as u32, self.config.max_replicas_per_stream);

        // Sort target regions by priority
        let mut sorted_regions = target_regions.to_vec();
        sorted_regions.sort_by_key(|r| r.priority);

        for region_input in sorted_regions {
            if replicas.len() >= target_replicas as usize {
                break;
            }

            let region_replicas = self.plan_region_replicas(
                nodes,
                primary,
                &region_input,
                viewer_distribution,
                &mut used_nodes,
                target_replicas - replicas.len() as u32,
            )?;

            replicas.extend(region_replicas);
        }

        // If we still need more replicas for erasure coding, add from any region
        while replicas.len() < target_replicas as usize {
            if let Some(replica) = self.plan_any_region_replica(nodes, primary, &mut used_nodes, viewer_distribution) {
                replicas.push(replica);
            } else {
                break;
            }
        }

        Ok(replicas)
    }

    /// Plan replicas for a specific region.
    fn plan_region_replicas(
        &self,
        nodes: &[NodeTopology],
        primary: &NodeTopology,
        region_input: &TargetRegionInput,
        viewer_distribution: &HashMap<String, u32>,
        used_nodes: &mut HashSet<String>,
        max_replicas: u32,
    ) -> anyhow::Result<Vec<PlannedReplica>> {
        let mut replicas = Vec::new();

        // Filter nodes in target region
        let region_nodes: Vec<&NodeTopology> = nodes.iter()
            .filter(|n| n.region == region_input.region)
            .filter(|n| !used_nodes.contains(&n.node_id))
            .filter(|n| self.check_anti_affinity(primary, n))
            .collect();

        if region_nodes.is_empty() {
            return Ok(replicas);
        }

        // Determine storage class based on viewer count
        let viewers = viewer_distribution.get(&region_input.region).copied().unwrap_or(0);
        let storage_class = if viewers > 1000 { StorageClass::Hot }
            else if viewers > 100 { StorageClass::Warm }
            else { StorageClass::Cold };

        // Sort by capacity score and cost
        let mut candidates = region_nodes;
        candidates.sort_by(|a, b| {
            let a_score = self.score_node(a, storage_class, viewers);
            let b_score = self.score_node(b, storage_class, viewers);
            b_score.partial_cmp(&a_score).unwrap()
        });

        let datacenters: HashSet<_> = region_input.datacenters.iter()
            .flat_map(|dc| dc.node_ids.iter().cloned())
            .collect();

        // Select replicas across different datacenters
        let mut dc_used = HashSet::new();
        for node in candidates {
            if replicas.len() >= max_replicas as usize {
                break;
            }

            // Check datacenter affinity
            if let Some(dc) = &region_input.datacenters.first().map(|d| d.datacenter.clone()) {
                if dc_used.contains(&dc) && self.config.min_anti_affinity_distance >= AntiAffinityDistance::Datacenter {
                    continue;
                }
                dc_used.insert(dc);
            }

            used_nodes.insert(node.node_id.clone());
            replicas.push(PlannedReplica {
                replica_id: format!("replica-{}-{}", region_input.region, uuid::Uuid::new_v4()),
                node_id: node.node_id.clone(),
                region: node.region.clone(),
                datacenter: node.datacenter.clone(),
                storage_class,
                role: if viewers > 1000 { ReplicaRole::Synchronous } else { ReplicaRole::Asynchronous },
                priority: region_input.priority,
                estimated_latency_ms: primary.latency_to_regions.get(&node.region).copied().unwrap_or(100),
            });
        }

        Ok(replicas)
    }

    /// Plan a replica from any available region.
    fn plan_any_region_replica(
        &self,
        nodes: &[NodeTopology],
        primary: &NodeTopology,
        used_nodes: &mut HashSet<String>,
        viewer_distribution: &HashMap<String, u32>,
    ) -> Option<PlannedReplica> {
        let candidates: Vec<&NodeTopology> = nodes.iter()
            .filter(|n| !used_nodes.contains(&n.node_id))
            .filter(|n| self.check_anti_affinity(primary, n))
            .collect();

        if candidates.is_empty() {
            return None;
        }

        // Prefer regions with viewers
        let mut best = candidates[0];
        let mut best_score = f32::MIN;

        for node in candidates {
            let viewers = viewer_distribution.get(&node.region).copied().unwrap_or(0);
            let score = self.score_node(node, StorageClass::Warm, viewers);
            if score > best_score {
                best_score = score;
                best = node;
            }
        }

        used_nodes.insert(best.node_id.clone());
        Some(PlannedReplica {
            replica_id: format!("replica-{}-{}", best.region, uuid::Uuid::new_v4()),
            node_id: best.node_id.clone(),
            region: best.region.clone(),
            datacenter: best.datacenter.clone(),
            storage_class: StorageClass::Warm,
            role: ReplicaRole::Asynchronous,
            priority: 999,
            estimated_latency_ms: primary.latency_to_regions.get(&best.region).copied().unwrap_or(200),
        })
    }

    /// Score a node for replica placement.
    fn score_node(&self, node: &NodeTopology, storage_class: StorageClass, viewers: u32) -> f32 {
        let capacity_ratio = 1.0 - (node.storage_used_bytes as f32 / node.storage_capacity_bytes.max(1) as f32);
        let capacity_score = (capacity_ratio - self.config.capacity_headroom).max(0.0);
        
        let cost_score = 1.0 / (1.0 + node.cost_per_gb_month as f32);
        
        let viewer_score = if viewers > 0 { (viewers as f32).ln() / 10.0 } else { 0.0 };
        
        let latency_score = 1.0; // Would calculate based on primary latency

        // Weighted combination
        let score = capacity_score * (1.0 - self.config.cost_weight) 
            + cost_score * self.config.cost_weight 
            + viewer_score * 0.2;

        // Penalty if storage class doesn't match
        if node.storage_class != storage_class {
            score * 0.5
        } else {
            score
        }
    }

    /// Check anti-affinity constraint.
    fn check_anti_affinity(&self, primary: &NodeTopology, candidate: &NodeTopology) -> bool {
        match self.config.min_anti_affinity_distance {
            AntiAffinityDistance::None => true,
            AntiAffinityDistance::Rack => {
                primary.rack.as_ref() != candidate.rack.as_ref()
            }
            AntiAffinityDistance::Datacenter => {
                primary.datacenter != candidate.datacenter
            }
            AntiAffinityDistance::Region => {
                primary.region != candidate.region
            }
            AntiAffinityDistance::Continent => {
                primary.continent != candidate.continent
            }
        }
    }

    /// Plan staging replicas.
    fn plan_staging(
        &self,
        nodes: &[NodeTopology],
        primary: &NodeTopology,
        replicas: &[PlannedReplica],
    ) -> anyhow::Result<StagingPlan> {
        let mut continent_staging = Vec::new();
        let mut region_staging = Vec::new();

        if self.config.continent_staging {
            // Add staging replica in each continent (except primary's)
            let continents: HashSet<_> = nodes.iter().map(|n| n.continent.clone()).collect();
            for continent in continents {
                if continent == primary.continent {
                    continue;
                }

                let continent_nodes: Vec<&NodeTopology> = nodes.iter()
                    .filter(|n| n.continent == continent)
                    .filter(|n| n.storage_class == StorageClass::Cold)
                    .collect();

                if let Some(node) = continent_nodes.first() {
                    continent_staging.push(PlannedReplica {
                        replica_id: format!("staging-continent-{}-{}", continent, uuid::Uuid::new_v4()),
                        node_id: node.node_id.clone(),
                        region: node.region.clone(),
                        datacenter: node.datacenter.clone(),
                        storage_class: StorageClass::Cold,
                        role: ReplicaRole::Staging,
                        priority: 100,
                        estimated_latency_ms: primary.latency_to_regions.get(&node.region).copied().unwrap_or(300),
                    });
                }
            }
        }

        if self.config.region_staging {
            // Add staging in regions without active replicas
            let replica_regions: HashSet<_> = replicas.iter().map(|r| r.region.clone()).collect();
            let all_regions: HashSet<_> = nodes.iter().map(|n| n.region.clone()).collect();

            for region in all_regions.difference(&replica_regions) {
                let region_nodes: Vec<&NodeTopology> = nodes.iter()
                    .filter(|n| n.region == *region)
                    .filter(|n| n.storage_class == StorageClass::Cold)
                    .collect();

                if let Some(node) = region_nodes.first() {
                    region_staging.push(PlannedReplica {
                        replica_id: format!("staging-region-{}-{}", region, uuid::Uuid::new_v4()),
                        node_id: node.node_id.clone(),
                        region: node.region.clone(),
                        datacenter: node.datacenter.clone(),
                        storage_class: StorageClass::Cold,
                        role: ReplicaRole::Staging,
                        priority: 200,
                        estimated_latency_ms: primary.latency_to_regions.get(region).copied().unwrap_or(200),
                    });
                }
            }
        }

        Ok(StagingPlan {
            continent_staging,
            region_staging,
            promotion_policy: PromotionPolicy {
                trigger: PromotionTrigger::PrimaryFailure,
                target_role: ReplicaRole::Synchronous,
                max_promotion_time_secs: 300,
            },
        })
    }

    /// Plan demand triggers.
    fn plan_demand_triggers(
        &self,
        viewer_distribution: &HashMap<String, u32>,
    ) -> anyhow::Result<Vec<DemandTriggerPlan>> {
        let mut triggers = Vec::new();

        for (region, viewers) in viewer_distribution {
            if *viewers > 100 { // Only plan for regions with significant viewers
                triggers.push(DemandTriggerPlan {
                    region: region.clone(),
                    min_viewers: *viewers / 2, // Trigger at half current viewers
                    trigger_delay_secs: 300,
                    cooldown_secs: 3600,
                    target_replicas: 2,
                    storage_class: StorageClass::Warm,
                });
            }
        }

        Ok(triggers)
    }

    /// Estimate monthly cost.
    fn estimate_cost(
        &self,
        primary: &NodeTopology,
        replicas: &[PlannedReplica],
        staging: &Option<StagingPlan>,
    ) -> f64 {
        let mut cost = 0.0;

        // Primary cost (hot storage)
        cost += primary.storage_capacity_bytes as f64 / (1024.0 * 1024.0 * 1024.0) * primary.cost_per_gb_month;

        // Replica costs
        for replica in replicas {
            let node = self.node_topology.get(&replica.node_id);
            if let Some(node) = node {
                cost += node.cost_per_gb_month * 100.0; // Assume 100GB per replica
            }
        }

        // Staging costs
        if let Some(staging) = staging {
            for replica in &staging.continent_staging {
                let node = self.node_topology.get(&replica.node_id);
                if let Some(node) = node {
                    cost += node.cost_per_gb_month * 50.0; // 50GB for staging
                }
            }
            for replica in &staging.region_staging {
                let node = self.node_topology.get(&replica.node_id);
                if let Some(node) = node {
                    cost += node.cost_per_gb_month * 50.0;
                }
            }
        }

        cost
    }

    /// Calculate durability score (0.0 - 1.0).
    fn calculate_durability(
        &self,
        primary: &NodeTopology,
        replicas: &[PlannedReplica],
        erasure_config: &ErasureConfig,
    ) -> f32 {
        // Base durability from erasure coding
        let k = erasure_config.k as f32;
        let m = erasure_config.m as f32;
        let base_durability = 1.0 - (1.0 / (k + m)).powi(m as i32 + 1);

        // Boost for geographic diversity
        let mut regions = HashSet::new();
        regions.insert(primary.region.clone());
        for r in replicas {
            regions.insert(r.region.clone());
        }

        let geo_boost = (regions.len() as f32 - 1.0) * 0.1;
        
        // Boost for anti-affinity
        let mut datacenters = HashSet::new();
        datacenters.insert(primary.datacenter.clone());
        for r in replicas {
            datacenters.insert(r.datacenter.clone());
        }
        let dc_boost = (datacenters.len() as f32 - 1.0) * 0.05;

        (base_durability + geo_boost + dc_boost).min(1.0)
    }

    /// Get active plan.
    pub fn get_plan(&self, stream_id: &str) -> Option<ReplicationPlanOutput> {
        self.active_plans.get(stream_id).map(|p| p.clone())
    }

    /// List all plans.
    pub fn list_plans(&self) -> Vec<ReplicationPlanOutput> {
        self.active_plans.iter().map(|p| p.value().clone()).collect()
    }

    /// Get planner stats.
    pub fn stats(&self) -> PlannerStats {
        PlannerStats {
            registered_nodes: self.node_topology.len(),
            active_plans: self.active_plans.len(),
        }
    }
}

