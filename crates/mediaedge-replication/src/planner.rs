    fn test_anti_affinity_distance() {
        let primary = NodeTopology {
            node_id: "node-1".to_string(),
            region: "us-east-1".to_string(),
            continent: "north-america".to_string(),
            datacenter: "dc1".to_string(),
            rack: Some("rack1".to_string()),
            storage_capacity_bytes: 1000_000_000_000,
            storage_used_bytes: 500_000_000_000,
            storage_class: StorageClass::Hot,
            cost_per_gb_month: 0.1,
            bandwidth_mbps: 10000,
            latency_to_regions: HashMap::new(),
            capabilities: NodeCapabilities::default(),
        };

        let same_dc = NodeTopology {
            node_id: "node-2".to_string(),
            region: "us-east-1".to_string(),
            continent: "north-america".to_string(),
            datacenter: "dc1".to_string(),
            rack: Some("rack2".to_string()),
            storage_capacity_bytes: 1000_000_000_000,
            storage_used_bytes: 300_000_000_000,
            storage_class: StorageClass::Hot,
            cost_per_gb_month: 0.1,
            bandwidth_mbps: 10000,
            latency_to_regions: HashMap::new(),
            capabilities: NodeCapabilities::default(),
        };

        let diff_dc = NodeTopology {
            node_id: "node-3".to_string(),
            region: "us-east-1".to_string(),
            continent: "north-america".to_string(),
            datacenter: "dc2".to_string(),
            rack: Some("rack1".to_string()),
            storage_capacity_bytes: 1000_000_000_000,
            storage_used_bytes: 200_000_000_000,
            storage_class: StorageClass::Hot,
            cost_per_gb_month: 0.1,
            bandwidth_mbps: 10000,
            latency_to_regions: HashMap::new(),
            capabilities: NodeCapabilities::default(),
        };

        let config = PlannerConfig {
            min_anti_affinity_distance: AntiAffinityDistance::Datacenter,
            ..Default::default()
        };

        let planner = ReplicationPlanner::new(config, Arc::new(mediaedge_observability::MetricsRegistry::new(&Default::default()).unwrap()));

        // Same datacenter should fail anti-affinity
        assert!(!planner.check_anti_affinity(&primary, &same_dc));

        // Different datacenter should pass
        assert!(planner.check_anti_affinity(&primary, &diff_dc));
    }

